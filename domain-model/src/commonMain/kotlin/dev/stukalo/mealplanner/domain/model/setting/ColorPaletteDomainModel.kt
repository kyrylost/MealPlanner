package dev.stukalo.mealplanner.domain.model.setting

/**
 * Domain model representing the available color palettes for the application.
 */
enum class ColorPaletteDomainModel {
    /** The default orange-based color palette. */
    ORANGE,

    /** A green-based color palette. */
    GREEN,

    /** A lime-based color palette. */
    LIME,

    /** A pink-based color palette. */
    PINK
}
